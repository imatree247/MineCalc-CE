def find_best_pixel(rgb):
    best=0
    diff=255*3
    for i in range(256):
        temp=0
        for j in range(3):
            temp+=abs(int(rgb[j])-int(palette[i][j]))
        if temp<diff:
            best=i
            diff=temp
    return best
def convert8bit(img):
    new=np.zeros(shape=(8,8),dtype=int)
    #first off, convert fro [y,x] to [x,y]
    for x in range(8):
        for y in range(8):
            color=find_best_pixel(img[x][y])
            new[x][y]=color
    return new
